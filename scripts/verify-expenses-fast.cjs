#!/usr/bin/env node
const assert=require('node:assert/strict');
const fs=require('node:fs');
const read=file=>fs.readFileSync(file,'utf8');
const page=read('app/(dashboard)/expenses/page.tsx');
const loading=read('app/(dashboard)/expenses/loading.tsx');
const error=read('app/(dashboard)/expenses/error.tsx');
const expenseAction=read('app/(dashboard)/expenses/actions.ts');
const shell=read('app/(dashboard)/layout.tsx');
const css=read('app/globals.css');
let count=0;const verify=(test,description)=>{assert.ok(test,description);count++};
verify(page.includes("import {Suspense} from 'react'"),'Must stream expense UI');
verify(page.includes('<Suspense fallback={<WorkspaceLoading/>}>'),'Must stream workspace auth verification');
verify(page.includes('<Suspense key={`expense-register-${page}-${q}`} fallback={<RegisterLoading/>}>'),'Must stream register independently');
verify(page.includes('getWorkspace()'),'Must verify authenticated business membership');
verify(page.includes(".eq('business_id',businessId)"),'Expense read must be tenant scoped');
verify(!page.includes('unstable_cache')&&!page.includes('revalidate:')&&!page.includes('cache('),'Must not cache private expenses across users');
verify(page.includes('const PAGE_SIZE=25'),'Read limit must be small');
verify(page.includes('.range(start,start+PAGE_SIZE)'),'Database query must be paginated');
verify(page.includes('hasNext'),'Next page must use the extra row');
verify(page.includes('Only displayed records are totalled'),'Page totals must not pretend to be accounting period totals');
verify(page.includes("['owner','manager','finance'].includes(role)"),'Expense form must be restricted to finance roles');
verify(page.includes("'expense_categories(name)'" )||page.includes('expense_categories(name)'),'Must preserve expense category');
verify(page.includes('minimumFractionDigits:2'),'Financial amounts must show kobo');
verify(page.includes('Try again')&&page.includes('/support'),'Recoverable error state required');
verify(loading.includes('Loading your expenses')&&!loading.includes('Opening your workspace'),'Route-specific loader required');
verify(error.startsWith("'use client'"),'Error boundary must be client component');
verify(error.includes('reset()')&&error.includes('Back to dashboard'),'Retry and navigation required');
verify(css.includes('.bo-expense-table td::before')&&css.includes('data-label'),'Accessible small-screen table labels');
verify(css.includes('@media(max-width:620px)'),'Mobile breakpoint required');
verify(!page.includes(".limit(200)"),'Avoid loading 200 expenses per navigation');
verify(expenseAction.includes("client.rpc('gl_record_paid_expense'"),'Existing guarded finance RPC must remain');
verify(shell.includes('getWorkspace()'),'Business shell remains authenticated');
verify(read('package.json').includes('check:expenses-speed'),'Dedicated regression command included');
verify(read('.github/workflows/verify.yml').includes('check:expenses-speed'),'CI must cover the fix');
console.log(`Expenses loading/performance guards passed (${count} assertions).`);
